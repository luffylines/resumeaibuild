const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const ts=require('typescript');
const source=fs.readFileSync('src/lib/admin-data-health.ts','utf8');
const compiled=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
const moduleRef={exports:{}};
vm.runInNewContext(compiled,{module:moduleRef,exports:moduleRef.exports});
const {adminDataWarning,adminEmptyData}=moduleRef.exports;
assert.equal(adminDataWarning('resumes',null),null);
const missing=adminDataWarning('profiles',{code:'42P01',message:'relation profiles does not exist'});
assert.equal(missing.resource,'profiles');
assert.match(missing.message,/missing or not exposed/);
const denied=adminDataWarning('ats_scans',{code:'42501',message:'permission denied'});
assert.match(denied.message,/Read access denied/);
const generic=adminDataWarning('activity_logs',{code:'UNKNOWN',message:'Internal secret-matching-token'});
assert.doesNotMatch(generic.message,/secret-matching-token/);
assert.equal(adminEmptyData().userTotal,0);
assert.equal(adminEmptyData().resumes.length,0);
assert.equal(adminEmptyData().users.length,0);
const app=fs.readFileSync('src/app/app/page.tsx','utf8');
assert.ok(!app.includes('href="/admin/login"'),'Normal client must not link to Admin Login');
assert.ok(!app.includes('sidebar-admin-area'),'Normal client sidebar must not expose admin workspace');
const admin=fs.readFileSync('src/components/admin-panel.tsx','utf8');
assert.match(admin,/demo\?sample:emptyLive/,'Live admin must never initialize demo numbers');
assert.match(admin,/setData\(emptyLive\)/,'Live DB failure must clear stale data');
assert.match(admin,/if\(payload\.source!=='supabase'\)/,'Live DB payload must be validated');
console.log('PASS admin: protected entry only, no live sample metrics, safe database error diagnostics');
